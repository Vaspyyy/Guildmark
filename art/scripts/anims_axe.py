"""
The axe's combat moves (vanilla's axes, held in one hand): brutal chops with the weight in the head, big shoulder
wind-ups and a hard stop where the bit bites. Third-person clips pose the skeleton; first-person clips move the
held item. Run:

    python3 -B art/scripts/anims_axe.py src/main/resources/assets/guildmark <preview-dir> <steve.png> <iron_axe.png>

Timings match Move.kt: a clip lasts as many ticks as its move, and its blow lands inside the move's hit window.
The axe's cutting edge faces where the arm points (its bit leads a chop when the arm travels the way the head does).
"""
