def hold(direction, blade):
    """The axe arm: pointing along [direction], the axe's handle turned as near [blade] as the grip allows."""
    return arm(direction, blade, geo=G)

def chop(theta, tilt=0.0, wrist=0.0):
    """The axe arm at [theta] degrees round a chop: 0 has the arm straight up and the head behind it, 90 the arm
    level with the head above the fist, 135 the arm angled down with the head ahead at chest height, 180 the arm
    straight down and the handle level. [tilt] leans the chop's plane to the right (a high-right to low-left
    stroke), negative to the left; [wrist] rolls the head out of that plane. The cutting edge faces along the arm."""
    t = math.radians(tilt)
    up = math.cos(t) * U + math.sin(t) * R
    a = math.radians(theta)
    d = math.cos(a) * up + math.sin(a) * F
    b = -math.cos(a) * F + math.sin(a) * up
    w = math.radians(wrist)
    b = b * math.cos(w) + np.cross(d, b) * math.sin(w)
    return hold(d, b)

def rest_arm():
    return hold(v(f=0.3, u=-1.0, r=0.05), F)

def guard_arm():
    """The free hand held up in front, loosely."""
    return free_arm(v(f=1.0, u=-0.6, r=-0.15))

# First person: where the item sits in the camera's frame (x right, y up, -z ahead; the grip's offset from the head
# changes with how the item is turned, so keys can be placed by the head: its place on the screen and its depth)
_HEAD_FP = apply(G.fp_display(), (9.5 / 16, 1 - 4.5 / 16, 0.5)) - G.fp_grip   # the middle of the axe's head
_TAN = math.tan(math.radians(35))

def fk(clip, t, hand, blade, edge=None, ease='inout'):
    off, q = fp(hand, blade, edge, geo=G)
    clip.key('item', t, q, pos=off, ease=ease)

def _head_q(sx, sy, depth, blade, edge=None, roll=0.0):
    """The head's place in the camera's frame and the item's turn, for a head at screen position (sx, sy)
    (-1 to 1 across and up) [depth] blocks ahead, the handle along [blade], the cutting edge facing [edge] (turned
    [roll] degrees about the handle, which shows more of the axe's flat to the camera)."""
    blade = unit(np.asarray(blade, float))
    if edge is not None:
        e0 = np.asarray(edge, float)
        edge = unit(e0 - np.dot(e0, blade) * blade)
        if roll:
            a = math.radians(roll)
            edge = math.cos(a) * edge + math.sin(a) * np.cross(blade, edge)
    q = fp(np.zeros(3), blade, edge, geo=G)[1]
    head = np.array([sx * _TAN * 16 / 9 * depth, sy * _TAN * depth, -depth])
    return head, q

def _put(clip, t, head, q, ease):
    hand = head - qmat(q) @ _HEAD_FP
    clip.key('item', t, q, pos=hand - FP_BASE - G.fp_grip, ease=ease)

def fh(clip, t, sx, sy, depth, blade, edge=None, ease='inout', roll=0.0):
    """A first-person key placed by where the axe's head sits on the screen."""
    head, q = _head_q(sx, sy, depth, blade, edge, roll)
    _put(clip, t, head, q, ease)

def fsweep(clip, t0, A, t1, B, n=2, prof='in'):
    """Keys between two head-placed poses A and B (tuples as fh takes them, without clip and time) so that a long
    swing keeps to the head's straight path across the screen instead of orbiting the grip; the head's progress
    follows the ease [prof]. B itself is keyed at [t1]."""
    hA, qA = _head_q(*A)
    hB, qB = _head_q(*B)
    for k in range(1, n + 2):
        u = k / (n + 1)
        sp = EASE[prof](u)
        _put(clip, t0 + (t1 - t0) * u, hA + (hB - hA) * sp, qslerp(qA, qB, sp), 'linear')

def _vplane(alpha):
    """The handle and leading edge of an axe turned [alpha] degrees about the camera's x axis: 0 has the handle
    up, 90 pointing away, 180 down, and the edge leads the way the head swings over the top."""
    a = math.radians(alpha)
    return vv(u=math.cos(a), f=math.sin(a)), vv(u=-math.sin(a), f=math.cos(a))

def fv(clip, t, sx, sy, depth, alpha, ease='inout', roll=65.0):
    """An overhead-chop key: the head at (sx, sy), the axe turned [alpha] degrees over the top and rolled [roll]
    about its handle to show its flat."""
    blade, edge = _vplane(alpha)
    fh(clip, t, sx, sy, depth, blade, edge, ease, roll)

def fvsweep(clip, t0, A, t1, B, n=2, prof='in', roll=65.0):
    """[fsweep] for an overhead chop; A and B are (sx, sy, depth, alpha) and the turn is followed angle by angle,
    so the axe goes over the top and not round the camera."""
    for k in range(1, n + 2):
        u = k / (n + 1)
        sp = EASE[prof](u)
        v_ = [x + (y - x) * sp for x, y in zip(A, B)]
        fv(clip, t0 + (t1 - t0) * u, *v_, ease='linear', roll=roll)

def cut(clip, t, hand, blade, motion, ease='inout'):
    """A first-person key whose cutting edge leads along [motion]."""
    b = unit(np.asarray(blade, float))
    m = np.asarray(motion, float)
    fk(clip, t, hand, b, unit(m - np.dot(m, b) * b), ease)

def rest(clip, t, ease='inout'):
    fk(clip, t, fp_rest(G), G.fp_blade, G.fp_edge, ease)

