def roll(name, length, flip_from, flip_to, low):
    c = tp(name, length, blend_in=1.0, blend_out=3.0)
    span = flip_to - flip_from
    c.key('torso', 0)
    c.key('torso', flip_from, qeuler(x=40), ease='out')
    c.key('torso', flip_to, qeuler(x=30), ease='linear')
    c.key('torso', length, qeuler(x=0), ease='inout')
    c.key('head', 0)
    c.key('head', flip_from, qeuler(x=40), ease='out')
    c.key('head', flip_to, qeuler(x=20), ease='linear')
    c.key('head', length, qeuler(x=0), ease='inout')
    c.mode('head', 'set')
    tucked_r = arm(v(f=1.0, u=-0.5, r=0.2), v(u=1.0, f=0.2))
    tucked_l = free_arm(v(f=1.0, u=-0.5, r=-0.2))
    c.key('right_arm', 0, rest_arm())
    c.key('right_arm', flip_from, tucked_r, ease='out')
    c.key('right_arm', flip_to, tucked_r, ease='linear')
    c.key('right_arm', length, rest_arm(), ease='inout')
    c.key('left_arm', 0, free_arm(D))
    c.key('left_arm', flip_from, tucked_l, ease='out')
    c.key('left_arm', flip_to, tucked_l, ease='linear')
    c.key('left_arm', length, free_arm(D), ease='inout')
    for leg, s in (('right_leg', 1), ('left_leg', -1)):
        c.key(leg, 0)
        c.key(leg, flip_from, qeuler(x=-100, z=4 * s), ease='out')
        c.key(leg, flip_to, qeuler(x=-80, z=4 * s), ease='linear')
        c.key(leg, flip_to + 1.5, qeuler(x=-30 if s > 0 else 10), ease='out')
        c.key(leg, length, qeuler(x=0), ease='inout')
    # The tumble itself: once round, forwards, low to the ground
    c.key('root', 0)
    c.key('root', flip_from, qeuler(x=30), pos=(0, low * 0.6, 0), ease='in')
    steps = 4
    for i in range(1, steps + 1):
        a = 30 + 330 * i / steps
        c.key('root', flip_from + span * i / steps, qeuler(x=a), pos=(0, low, 0), ease='linear')
    c.key('root', length, qeuler(x=360), pos=(0, 0, 0), ease='out')
    return c

